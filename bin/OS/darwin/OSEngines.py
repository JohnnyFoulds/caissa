"""
bin/OS/darwin/OSEngines.py — macOS engine registry (Apple Silicon)

Strategy:
  1. Load linux and win32 OSEngines (using a stub FasterCode) to get the full
     upstream engine list with all metadata (author, version, url, elo, UCI
     defaults, nodes_compatible, MultiPV) for free.
  2. Override the 4-5 engines that have native arm64 builds.
  3. For every other engine, remap path_exe to the wrapper script generated by
     gen_darwin_engines.py that tunnels through the Docker bridge container.
  4. Drop engines whose wrapper does not exist (bridge not set up / probe failed).
"""
import importlib.util
import os
import stat
import subprocess
import sys

import FasterCode

from Code.Base.Constantes import ENG_FIXED, ENG_INTERNAL
from Code.Engines import Engines
from Code.Z import Util

# ── Paths ──────────────────────────────────────────────────────────────────────
_HERE = os.path.dirname(os.path.abspath(__file__))          # bin/OS/darwin
_BIN = os.path.dirname(os.path.dirname(_HERE))              # bin
_DARWIN_ENGINES = os.path.join(_HERE, "Engines")
_REPO_ENGINES_LINUX = os.path.join(os.path.dirname(_HERE), "linux", "Engines")
_REPO_ENGINES_WIN32 = os.path.join(os.path.dirname(_HERE), "win32", "Engines")

# Module-level caches: _load_upstream and read_engines are called multiple times
# per process (once at startup, again when engine-selector dialogs open).
_upstream_cache: dict = {}
_read_engines_cache: dict | None = None
_docker_available: bool | None = None  # None = not yet probed

# Keys that have native arm64 binaries — DO NOT bridge these.
# eguzki/eguzkilore are intentionally absent: the linux ELF was previously registered
# as native (via a symlink), which caused exec failures.  Let them bridge like the
# other ~90 Docker engines.
_NATIVE_KEYS = {"stockfish", "lc0", "irina", "drawfish"} | {
    f"maia-{lvl}" for lvl in list(range(1100, 2000, 100)) + [2200]
}


# ── Load upstream OSEngines for a platform ─────────────────────────────────────
def _load_upstream(platform: str, folder_engines: str) -> dict:
    cache_key = (platform, folder_engines)
    if cache_key in _upstream_cache:
        return _upstream_cache[cache_key]

    fake_fc = type(sys)("FasterCode")
    fake_fc.bmi2 = lambda: False
    fake_fc.set_fen = lambda fen: None
    saved = sys.modules.get("FasterCode")
    sys.modules["FasterCode"] = fake_fc

    path = os.path.join(os.path.dirname(_HERE), platform, "OSEngines.py")
    spec = importlib.util.spec_from_file_location(f"OSEngines_{platform}", path)
    mod = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(mod)

    if saved is None:
        del sys.modules["FasterCode"]
    else:
        sys.modules["FasterCode"] = saved

    result = mod.read_engines(folder_engines)
    _upstream_cache[cache_key] = result
    return result


# ── Helpers ───────────────────────────────────────────────────────────────────
def _ensure_exec(path: str) -> None:
    """Mark a file executable if it isn't already."""
    if os.path.isfile(path) and not os.access(path, os.X_OK):
        try:
            os.chmod(path, os.stat(path).st_mode | stat.S_IXUSR)
        except OSError:
            pass


def _darwin_exe(folder_name: str, exe_name: str) -> str:
    return os.path.join(_DARWIN_ENGINES, folder_name, exe_name)


def _probe_docker() -> bool:
    """One-time probe: is the lucas-engines container reachable?  Result is cached."""
    global _docker_available
    if _docker_available is not None:
        return _docker_available
    try:
        r = subprocess.run(
            ["docker", "inspect", "-f", "{{.State.Status}}", "lucas-engines"],
            capture_output=True, text=True, timeout=2,
        )
        _docker_available = r.returncode == 0 and r.stdout.strip() in ("running", "paused")
    except Exception:
        _docker_available = False
    return _docker_available


# ── Main entry point called by Code/__init__.py ───────────────────────────────
def read_engines(folder_engines: str) -> dict:
    """
    Returns {key: Engine} for all available macOS engines.
    folder_engines is bin/OS/darwin/Engines (passed by __init__.py).
    """
    global _read_engines_cache
    if _read_engines_cache is not None:
        return _read_engines_cache

    dic: dict = {}

    # ── 1. Load upstream linux + win32 engine metadata ──────────────────────
    try:
        linux_engines = _load_upstream("linux", _REPO_ENGINES_LINUX)
    except Exception:
        linux_engines = {}
    try:
        win32_engines = _load_upstream("win32", _REPO_ENGINES_WIN32)
    except Exception:
        win32_engines = {}

    # Merge; linux wins for shared keys (matches gen_darwin_engines.py priority).
    # win32-only keys are added on top (no conflict).
    combined = {**win32_engines, **linux_engines}

    # ── 2. Native arm64 engines ──────────────────────────────────────────────
    def _native(key: str, exe: str) -> Engines.Engine | None:
        """Copy an upstream engine entry and redirect its path to a darwin binary."""
        template = combined.get(key)
        if template is None:
            return None
        eng = template.clone()
        eng.path_exe = Util.relative_path(_darwin_exe(key, exe))
        _ensure_exec(eng.path_exe)
        eng.set_type(ENG_INTERNAL)
        return eng

    # Stockfish 18 (brew, arm64 native)
    sf = _native("stockfish", "stockfish-18-arm64")
    if sf:
        dic["stockfish"] = sf

    # irina (compiled from source, arm64 native)
    ir = _native("irina", "irina")
    if ir:
        dic["irina"] = ir

    # Lc0 0.32.1 (vendored real binary, not the Homebrew bash wrapper)
    lc0_template = combined.get("lc0")
    if lc0_template:
        lc0 = lc0_template.clone()
        lc0.path_exe = Util.relative_path(_darwin_exe("lc0", "Lc0-0.32.1"))
        _ensure_exec(lc0.path_exe)
        lc0.set_type(ENG_INTERNAL)
        dic["lc0"] = lc0

    # Maia (10 human-like levels, share the single lc0/ binary — no second copy)
    for key in [f"maia-{lvl}" for lvl in list(range(1100, 2000, 100)) + [2200]]:
        tmpl = combined.get(key)
        if tmpl is None:
            continue
        eng = tmpl.clone()
        eng.path_exe = Util.relative_path(_darwin_exe("lc0", "Lc0-0.32.1"))
        _ensure_exec(eng.path_exe)
        # Update WeightsFile to darwin path
        level = key.split("-")[1]
        weights = _darwin_exe("maia", f"maia-{level}.pb.gz")
        if os.path.isfile(weights):
            eng.set_uci_option("WeightsFile", weights)
        eng.set_type(ENG_INTERNAL)
        dic[key] = eng

    # ── 3. Bridged engines (wrapper scripts generated by gen_darwin_engines.py) ─
    # Skip entirely when Docker is unavailable — no wrapper will work, and the
    # probe is cached so this is instant after the first call.
    if _probe_docker():
        for key, tmpl in combined.items():
            if key in dic:
                continue   # already registered as native
            if key in _NATIVE_KEYS:
                continue   # native-only, skip if not built

            # Reconstruct expected wrapper path
            exe_name = os.path.basename(tmpl.path_exe)
            parts = tmpl.path_exe.replace("\\", "/").split("/")
            try:
                eng_idx = [p.lower() for p in parts].index("engines")
                folder = parts[eng_idx + 1]
            except (ValueError, IndexError):
                folder = exe_name

            wrapper = _darwin_exe(folder, exe_name)
            if not os.path.isfile(wrapper):
                continue   # wrapper not generated yet

            eng = tmpl.clone()
            eng.path_exe = Util.relative_path(wrapper)
            _ensure_exec(eng.path_exe)
            eng.set_type(ENG_INTERNAL)
            dic[key] = eng

    # ── 4. Extra darwin-only engines (not in upstream linux/win32 registries) ───
    # These are native arm64 binaries built specifically for this fork.
    _EXTRA_ENGINES = [
        # (key, name, author, elo, folder, exe_name, multiPV, nodes_compatible)
        ("drawfish", "Drawfish", "Nathan Rugg", 2400, "drawfish", "drawfish", 500, True),
    ]
    for key, name, author, elo, folder, exe_name, multiPV, nodes_compat in _EXTRA_ENGINES:
        exe = _darwin_exe(folder, exe_name)
        if not os.path.isfile(exe):
            continue
        eng = Engines.Engine()
        eng.key = key
        eng.name = name
        eng.autor = author
        eng.url = "https://github.com/nmrugg/Drawfish"
        eng.version = ""
        eng.elo = elo
        eng.maxMultiPV = multiPV
        eng.nodes_compatible = nodes_compat
        eng.path_exe = Util.relative_path(exe)
        _ensure_exec(eng.path_exe)
        eng.set_type(ENG_INTERNAL)
        dic[key] = eng

    # ── 5. Retro Engine (Battle Chess emulator, ENG_FIXED) ───────────────────
    _retro_exe = os.path.normpath(os.path.join(_HERE, "..", "..", "tools", "caissa-retro"))
    if os.path.isfile(_retro_exe):
        retro = Engines.Engine()
        retro.key = "caissa-retro"
        retro.name = "Battle Chess Retro Engine"
        retro.autor = "Interplay / Dragon (original); Caissa wrapper"
        retro.url = ""
        retro.version = "1.0"
        retro.elo = 800
        retro.maxMultiPV = 1
        retro.nodes_compatible = False
        retro.path_exe = Util.relative_path(_retro_exe)
        _ensure_exec(retro.path_exe)
        retro.set_type(ENG_FIXED)
        dic["caissa-retro"] = retro

    _read_engines_cache = dic
    return dic


def li_engines_fixed_elo() -> tuple:
    """
    Subset of engines suitable for fixed-Elo play (Lucas-Elo ladder etc.).
    We expose what we actually have — the tuples are (key, min_elo, max_elo).
    """
    return (
        ("stockfish", 1400, 3100),
        ("lc0",       2000, 3332),
        ("irina",      900, 1800),
    ) + tuple(
        (f"maia-{lvl}", lvl - 50, lvl + 50)
        for lvl in list(range(1100, 2000, 100)) + [2200]
        if os.path.isfile(_darwin_exe("maia", f"maia-{lvl}.pb.gz"))
    )
